"""Write the narration's word times into a HyperFrames piece, so the picture is placed on words, never on typed seconds.

    .venv/bin/python tools/sync_voice_times.py motion/<topic>/<part> [--tail 2.3]

Reads <piece>/voice/timings.json and replaces the block between `/* VOICE-TIMES */` and `/* END VOICE-TIMES */` in
<piece>/compositions/film.html with `const VT = {...}` and a helper `W(beat, word, n = 1)` (the start of the n-th
time `word` is spoken in that beat; punctuation and case ignored). `VT[beat].start` / `.end` are the beat's bounds.
Also sets the film length (last word + tail) on every `data-duration` in index.html and on the film's root clip.
Run it after every voice change, then rebuild the sound (tools/sound_mix.py) and render.
"""
import json, re, sys
from pathlib import Path


def norm(w):
    return re.sub(r'[.,:;!?"“”]+$', "", w.lower())


def main(piece, tail=2.3):
    piece = Path(piece)
    tm = json.loads((piece / "voice" / "timings.json").read_text())
    beats = json.loads((piece / "beats.json").read_text())["beats"]
    vt = {}
    for b, t in zip(beats, tm):
        vt[b["id"]] = {"start": round(t["start"], 3), "end": round(t["end"], 3),
                       "w": [[norm(w), round(s, 3)] for w, s, _ in t["words"]]}
    length = round(tm[-1]["end"] + tail, 2)
    block = ("/* VOICE-TIMES (generated by tools/sync_voice_times.py from voice/timings.json; do not edit) */\n"
             f"    const VT = {json.dumps(vt, separators=(',', ':'))};\n"
             f"    const LENGTH = {length};\n"
             "    function W(beat, word, n = 1) {\n"
             "      const hits = VT[beat].w.filter((x) => x[0] === word.toLowerCase());\n"
             "      if (hits.length < n) throw new Error(`no word '${word}' #${n} in beat ${beat}`);\n"
             "      return hits[n - 1][1];\n"
             "    }\n"
             "    /* END VOICE-TIMES */")
    film = piece / "compositions" / "film.html"
    s = film.read_text()
    s, k = re.subn(r"/\* VOICE-TIMES.*?/\* END VOICE-TIMES \*/", lambda m: block, s, flags=re.S)
    if k != 1:
        sys.exit("film.html needs one /* VOICE-TIMES */ ... /* END VOICE-TIMES */ block")
    s = re.sub(r'(id="desk" class="[^"]*" data-start="0" data-duration=")[\d.]+', rf"\g<1>{length}", s)
    film.write_text(s)
    idx = piece / "index.html"
    i = re.sub(r'(data-duration=")[\d.]+(")', rf"\g<1>{length}\2", idx.read_text())
    idx.write_text(i)
    print(f"{len(vt)} beats, length {length} s -> film.html, index.html")


if __name__ == "__main__":
    a = sys.argv[1:]
    main(a[0], float(a[a.index("--tail") + 1]) if "--tail" in a else 2.3)
